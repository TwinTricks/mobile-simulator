/** iOS turns the charge red at 20% and below. */
export const LOW_BATTERY = 20;

export function BatteryIcon({ level = 100 }: { level?: number }) {
  // Masks are looked up by id across the whole page, and every device draws one of these.
  const mask = useId();
  const width = Math.max(1.5, (21 * level) / 100);
  return (
    <svg width="27.23" height="13" viewBox="342.2 26.6 27.23 13" fill="none" aria-hidden>
      <mask id={mask} fill="white">
        <path d={BATTERY_OUTLINE} />
      </mask>
      {/* Twice the stroke, clipped to the shape: a 1px border drawn on the inside. */}
      <path
        opacity="0.35"
        d={BATTERY_OUTLINE}
        strokeWidth="2"
        stroke="currentColor"
        mask={`url(#${mask})`}
      />
      <path
        opacity="0.4"
        d="M368.1 31.2667V35.2667C368.905 34.9279 369.428 34.1398 369.428 33.2667C369.428 32.3935 368.905 31.6054 368.1 31.2667"
        fill="currentColor"
      />
      <rect
        x="344"
        y="28.6"
        width={width}
        height="9"
        rx={Math.min(2.5, width / 2)}
        fill={level <= LOW_BATTERY ? "#ff3b30" : "currentColor"}
      />
    </svg>
  );
}
